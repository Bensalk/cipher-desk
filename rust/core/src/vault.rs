//! Saved passwords in the operating system's vault (S4, S5, SA-9, I8).
//!
//! - Windows: Credential Manager. Linux: Secret Service (GNOME Keyring, KWallet).
//! - Android: not here; the app uses the Android Keystore from Kotlin, because
//!   unlocking needs the system biometric prompt.
//!
//! Rules:
//! - Passwords are never written anywhere else. If no vault is available the
//!   save fails with [`VaultError::Unavailable`]; there is no file fallback (I8).
//! - Entries are named by an opaque connection id, so the vault list does not
//!   reveal host names or usernames.
//! - Passwords read from the vault are returned as [`SecretString`].

use std::sync::{Arc, Mutex};

use keyring_core::{CredentialStore, Entry, Error as KError};

use crate::secret::SecretString;

/// Service name shown in the OS vault.
pub const SERVICE: &str = "io.github.securerdpviewer";

/// Why a vault operation failed. Messages contain no secrets or names.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum VaultError {
    /// No password is saved for this connection.
    #[error("no saved password for this connection")]
    NotFound,
    /// No secure vault exists on this device (e.g. Linux without a keyring).
    #[error("no secure password storage is available on this device")]
    Unavailable,
    /// The vault exists but is locked or access was refused.
    #[error("the password storage is locked or access was refused")]
    Locked,
    /// The connection id is not valid.
    #[error("invalid connection id")]
    InvalidId,
}

static STORE_READY: Mutex<bool> = Mutex::new(false);

/// Installs the platform store once. Failures are not cached, so a keyring
/// that becomes available later (e.g. after login) is picked up.
fn ensure_store() -> Result<(), VaultError> {
    let mut ready = STORE_READY.lock().map_err(|_| VaultError::Unavailable)?;
    if *ready || keyring_core::get_default_store().is_some() {
        *ready = true;
        return Ok(());
    }
    let store = platform_store()?;
    keyring_core::set_default_store(store);
    *ready = true;
    Ok(())
}

#[cfg(windows)]
fn platform_store() -> Result<Arc<CredentialStore>, VaultError> {
    windows_native_keyring_store::Store::new()
        .map(|s| s as Arc<CredentialStore>)
        .map_err(|_| VaultError::Unavailable)
}

#[cfg(target_os = "linux")]
fn platform_store() -> Result<Arc<CredentialStore>, VaultError> {
    zbus_secret_service_keyring_store::Store::new()
        .map(|s| s as Arc<CredentialStore>)
        .map_err(|_| VaultError::Unavailable)
}

#[cfg(not(any(windows, target_os = "linux")))]
fn platform_store() -> Result<Arc<CredentialStore>, VaultError> {
    Err(VaultError::Unavailable)
}

/// Connection ids are generated by the app; accept only safe characters.
fn account(connection_id: &str) -> Result<String, VaultError> {
    let ok = !connection_id.is_empty()
        && connection_id.len() <= 64
        && connection_id
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_');
    if ok {
        Ok(format!("connection-{connection_id}"))
    } else {
        Err(VaultError::InvalidId)
    }
}

fn entry(connection_id: &str) -> Result<Entry, VaultError> {
    // Validate before touching the OS store.
    let user = account(connection_id)?;
    ensure_store()?;
    Entry::new(SERVICE, &user).map_err(map_err)
}

fn map_err(e: KError) -> VaultError {
    match e {
        KError::NoEntry => VaultError::NotFound,
        KError::NoStorageAccess(_) => VaultError::Locked,
        KError::NoDefaultStore | KError::PlatformFailure(_) => VaultError::Unavailable,
        _ => VaultError::Unavailable,
    }
}

/// Saves (or replaces) the password for a connection.
pub fn save(connection_id: &str, password: &SecretString) -> Result<(), VaultError> {
    if password.is_empty() {
        return Err(VaultError::NotFound);
    }
    entry(connection_id)?
        .set_password(password.expose())
        .map_err(map_err)
}

/// Reads the saved password for a connection.
pub fn load(connection_id: &str) -> Result<SecretString, VaultError> {
    entry(connection_id)?
        .get_password()
        .map(SecretString::new)
        .map_err(map_err)
}

/// True if a password is saved for this connection.
pub fn exists(connection_id: &str) -> Result<bool, VaultError> {
    match load(connection_id) {
        Ok(_) => Ok(true),
        Err(VaultError::NotFound) => Ok(false),
        Err(e) => Err(e),
    }
}

/// Deletes the saved password. Deleting one that does not exist is not an error.
pub fn delete(connection_id: &str) -> Result<(), VaultError> {
    match entry(connection_id)?.delete_credential().map_err(map_err) {
        Ok(()) | Err(VaultError::NotFound) => Ok(()),
        Err(e) => Err(e),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn use_mock_store() -> Result<(), String> {
        let store = keyring_core::mock::Store::new().map_err(|e| e.to_string())?;
        keyring_core::set_default_store(store);
        if let Ok(mut r) = STORE_READY.lock() {
            *r = true;
        }
        Ok(())
    }

    fn sample() -> SecretString {
        SecretString::new(["vault", "test", "7"].join("-"))
    }

    #[test]
    fn save_load_delete_round_trip() -> Result<(), String> {
        use_mock_store()?;
        let id = "p-roundtrip";
        assert_eq!(exists(id), Ok(false));
        save(id, &sample()).map_err(|e| e.to_string())?;
        assert_eq!(exists(id), Ok(true));
        let got = load(id).map_err(|e| e.to_string())?;
        assert_eq!(got.expose(), sample().expose());
        delete(id).map_err(|e| e.to_string())?;
        assert_eq!(load(id).err(), Some(VaultError::NotFound));
        // Deleting again is fine.
        assert_eq!(delete(id), Ok(()));
        Ok(())
    }

    #[test]
    fn ids_are_opaque_and_validated() {
        assert_eq!(account("p1").as_deref(), Ok("connection-p1"));
        for bad in ["", "office pc", "../x", "a@b", &"x".repeat(65)] {
            assert_eq!(account(bad), Err(VaultError::InvalidId), "{bad:?}");
        }
    }

    #[test]
    fn empty_password_is_not_saved() -> Result<(), String> {
        use_mock_store()?;
        assert!(save("p-empty", &SecretString::default()).is_err());
        assert_eq!(exists("p-empty"), Ok(false));
        Ok(())
    }

    #[test]
    fn error_messages_contain_no_details() {
        for e in [
            VaultError::NotFound,
            VaultError::Unavailable,
            VaultError::Locked,
            VaultError::InvalidId,
        ] {
            let m = e.to_string();
            assert!(!m.contains("connection-") && !m.is_empty(), "{m}");
        }
    }
}
