#!/usr/bin/env python3
"""Draws the app icon (original artwork, Apache-2.0) and writes every size the
platforms need. Run from the repository root: python3 tools/icon/make_icons.py
Needs Pillow. The same shapes are written as SVG for Linux."""
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
S = 1024  # drawing size; scaled down for each output
TEAL, DARK, WHITE, AMBER = "#00796B", "#004D40", "#FFFFFF", "#FFC107"

# Geometry on a 1024 grid (shared by the PNG and SVG versions).
TILE = (64, 64, 960, 960, 200)          # x0, y0, x1, y1, corner radius
SCREEN = (192, 232, 832, 664, 56)       # monitor outline
STAND = [(452, 664), (572, 664), (612, 776), (412, 776)]
BASE = (332, 776, 692, 828, 26)
LOCK_BODY = (402, 420, 622, 590, 28)
SHACKLE = (442, 316, 582, 470)          # bounding box of the arc
STROKE = 52


def draw_png() -> Image.Image:
    im = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    x0, y0, x1, y1, r = TILE
    d.rounded_rectangle((x0, y0, x1, y1), r, fill=TEAL)
    x0, y0, x1, y1, r = SCREEN
    d.rounded_rectangle((x0, y0, x1, y1), r, fill=DARK, outline=WHITE, width=STROKE)
    d.polygon(STAND, fill=WHITE)
    x0, y0, x1, y1, r = BASE
    d.rounded_rectangle((x0, y0, x1, y1), r, fill=WHITE)
    d.arc(SHACKLE, 180, 360, fill=AMBER, width=40)
    d.line((SHACKLE[0] + 20, 392, SHACKLE[0] + 20, 440), fill=AMBER, width=40)
    d.line((SHACKLE[2] - 20, 392, SHACKLE[2] - 20, 440), fill=AMBER, width=40)
    x0, y0, x1, y1, r = LOCK_BODY
    d.rounded_rectangle((x0, y0, x1, y1), r, fill=AMBER)
    d.ellipse((494, 478, 530, 514), fill=DARK)
    d.rectangle((503, 500, 521, 552), fill=DARK)
    return im


def svg() -> str:
    def rr(b, fill, extra=""):
        x0, y0, x1, y1, r = b
        return f'<rect x="{x0}" y="{y0}" width="{x1-x0}" height="{y1-y0}" rx="{r}" fill="{fill}"{extra}/>'
    pts = " ".join(f"{x},{y}" for x, y in STAND)
    sx0, sy0, sx1, sy1 = SHACKLE
    cx, rad = (sx0 + sx1) / 2, (sx1 - sx0) / 2 - 20
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {S} {S}">
  <!-- Secure RDP Viewer icon. Original artwork, Apache-2.0. Generated by tools/icon/make_icons.py -->
  {rr(TILE, TEAL)}
  {rr(SCREEN, DARK, f' stroke="{WHITE}" stroke-width="{STROKE}"')}
  <polygon points="{pts}" fill="{WHITE}"/>
  {rr(BASE, WHITE)}
  <path d="M {cx-rad} 440 V 392 A {rad} {rad} 0 0 1 {cx+rad} 392 V 440" fill="none" stroke="{AMBER}" stroke-width="40"/>
  {rr(LOCK_BODY, AMBER)}
  <circle cx="512" cy="496" r="18" fill="{DARK}"/>
  <rect x="503" y="500" width="18" height="52" fill="{DARK}"/>
</svg>
"""


def main() -> None:
    big = draw_png()
    out = lambda p: (ROOT / p).parent.mkdir(parents=True, exist_ok=True) or ROOT / p
    # Android launcher icons.
    for name, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        big.resize((px, px), Image.LANCZOS).save(out(f"app/android/app/src/main/res/mipmap-{name}/ic_launcher.png"))
    # Windows (exe resource).
    big.save(out("app/windows/runner/resources/app_icon.ico"),
             sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
    # Linux (hicolor theme) and the AppImage.
    for px in (64, 128, 256, 512):
        big.resize((px, px), Image.LANCZOS).save(out(f"packaging/linux/icons/{px}x{px}/secure-rdp-viewer.png"))
    out("packaging/linux/icons/scalable/secure-rdp-viewer.svg").write_text(svg())


if __name__ == "__main__":
    main()
